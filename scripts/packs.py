#!/usr/bin/env python3
"""Generate one context pack per role: context/<role>.md = task + plan + only the contract sections that role needs.

Run after every contract change, then commit on the `contract` branch. Packs are generated; never edit them by hand.
"""
import hashlib
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SECTIONS = {
    "api": [1, 2, 3, 4, 7, 8],
    "worker": [1, 2, 3, 4, 5, 6, 10],
    "extract": [4, 8, 9],
    "evals-data": [2, 5, 9, 10],
    "tests": "all",
    "reviewer": "all",
}


def split_contract(text):
    parts = re.split(r"(?m)^(?=## \d+\. )", text)
    out = {}
    for part in parts:
        m = re.match(r"## (\d+)\. ", part)
        if m:
            out[int(m.group(1))] = part.strip()
    return out


def main():
    contract_text = (ROOT / "docs/contract.md").read_text()
    digest = hashlib.sha256(contract_text.encode()).hexdigest()[:12]
    sections = split_contract(contract_text)
    (ROOT / "context").mkdir(exist_ok=True)
    for role, wanted in SECTIONS.items():
        body = [f"# Context pack: {role}",
                f"Generated by scripts/packs.py from docs/contract.md (sha256 {digest}). Do not edit; this is everything you need.",
                ""]
        for name in ("tasks", "plans"):
            f = ROOT / name / f"{role}.md"
            if f.exists():
                body += [f.read_text().strip(), ""]
        if wanted == "all":
            body += ["# Contract (full)", contract_text.strip(), "",
                     "# Brief (full)", (ROOT / "parallel-filings-brief.md").read_text().strip()]
        else:
            body.append("# Contract sections you need")
            body += [sections[n] for n in wanted]
        text = "\n".join(body).rstrip() + "\n"
        (ROOT / "context" / f"{role}.md").write_text(text)
        print(f"context/{role}.md  {len(text.split())} words  sections {wanted}")


if __name__ == "__main__":
    main()
