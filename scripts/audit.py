#!/usr/bin/env python3
"""Provenance audit: writes evidence/audit.md from git history, agent clones, chained logs and transcripts.

Checks:
  1. every commit on feat/<role> is stamped, and its session id matches sessions.log for that role
  2. every file a role's own commits touched is inside its write allowlist
  3. fingerprint proofs: forbidden blobs are absent from a clone's object store
  4. hash chains of every guard and gate log verify
  5. timeline: evals-data started only after extract ended
  6. tests read-before-write: every tests/ file the tests agent read was its own or in its base
  7. scorecard per role: files on disk, tool calls, denials, gate attempts, turns, cost, duration
"""
import fnmatch
import json
import os
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
AGENTS = Path(os.environ.get("AGENTS_DIR", REPO.parent / "litigence-agents"))
sys.path.insert(0, str(REPO / ".claude" / "hooks"))
import chainlog  # noqa: E402

ROLES = ["api", "worker", "extract", "evals-data", "tests", "reviewer"]
CFG = json.loads((REPO / ".claude" / "roles.json").read_text())


def git(*args, cwd=REPO):
    r = subprocess.run(["git", *args], cwd=cwd, capture_output=True, text=True)
    return r.stdout if r.returncode == 0 else ""


def blob_absent(clone, sha):
    return subprocess.run(["git", "cat-file", "-e", sha], cwd=clone, capture_output=True).returncode != 0


def sessions():
    out = []
    f = AGENTS / "sessions.log"
    for line in (f.read_text().splitlines() if f.exists() else []):
        parts = line.split()
        if len(parts) >= 3:
            out.append({"ts": parts[0], "event": parts[1], "role": parts[2], "session": parts[3] if len(parts) > 3 else ""})
    return out


def read_jsonl(path):
    rows = []
    for line in (path.read_text().splitlines() if path.exists() else []):
        try:
            rows.append(json.loads(line))
        except ValueError:
            pass
    return rows


def main():
    sess = sessions()
    md = ["# Provenance audit", "", f"Generated by `scripts/audit.py` at `main` {git('rev-parse', '--short', 'main').strip()}.", ""]
    ok_all = True

    # 1 + 2: stamps and scope
    md += ["## 1. Commit stamps and scope", "", "| Role | Own commits | Stamped | Session matches sessions.log | Files outside slice |", "|---|---|---|---|---|"]
    for role in ROLES:
        if not git("rev-parse", "--verify", f"refs/heads/feat/{role}"):
            continue
        clone = AGENTS / role
        base = (clone / ".claude" / "base").read_text().strip() if (clone / ".claude" / "base").exists() else "main"
        others = [f"^feat/{o}" for o in ROLES if o != role and git("rev-parse", "--verify", f"refs/heads/feat/{o}")]
        commits = [c for c in git("rev-list", "--no-merges", f"{base}..feat/{role}", "^contract", *others).split() if c]
        role_sessions = {s["session"] for s in sess if s["role"] == role}
        stamped = match = 0
        for c in commits:
            msg = git("log", "-1", "--format=%B", c)
            r = next((l.split(":", 1)[1].strip() for l in msg.splitlines() if l.startswith("Agent-Role:")), None)
            s = next((l.split(":", 1)[1].strip() for l in msg.splitlines() if l.startswith("Agent-Session:")), None)
            stamped += r == role
            match += s in role_sessions
        touched = {f for f in git("log", "--no-merges", "--format=", "--name-only", f"{base}..feat/{role}", "^contract", *others).splitlines() if f}
        outside = sorted(f for f in touched if not any(fnmatch.fnmatch(f, p) for p in CFG["roles"][role]["write"]))
        good = stamped == len(commits) and match == len(commits) and not outside
        ok_all &= good
        md.append(f"| {role} | {len(commits)} | {stamped}/{len(commits)} | {match}/{len(commits)} | {', '.join(outside) or 'none'} |")

    # 3: fingerprints
    md += ["", "## 2. Fingerprint proofs (forbidden content absent from a clone's object store)", "",
           "Git names every file version by its content hash. If a clone's object store lacks that hash, that clone never held those bytes.", "",
           "| Clone | Must never have held | Blobs checked | Absent |", "|---|---|---|---|"]
    proofs = [("extract", ["evals/"]), ("evals-data", ["extractor/", "app/", "worker/"]), ("tests", ["app/", "worker/", "extractor/"])]
    for role, prefixes in proofs:
        clone = AGENTS / role
        if not clone.exists():
            continue
        blobs = []
        for line in git("ls-tree", "-r", "main").splitlines():
            meta, path = line.split("\t", 1)
            if any(path.startswith(p) for p in prefixes) and not path.endswith("__init__.py"):
                blobs.append(meta.split()[2])
        absent = sum(blob_absent(clone, b) for b in blobs)
        good = absent == len(blobs)
        ok_all &= good
        md.append(f"| {role} | {', '.join(prefixes)} | {len(blobs)} | {absent}/{len(blobs)} {'✅' if good else '❌'} |")

    # negative controls: the checks must be able to fail
    md += ["", "### Negative controls (the checks can fail)", ""]
    ev = [l.split()[2] for l in git("ls-tree", "-r", "main", "--", "evals/notices.jsonl").splitlines()]
    present_in_repo = bool(ev) and not blob_absent(REPO, ev[0])
    ok_all &= present_in_repo
    md.append(f"- Fingerprint check pointed at the architect repo, which does hold `evals/notices.jsonl`: {'reports present ✅' if present_in_repo else 'did not detect it ❌'}")
    import shutil, tempfile
    src = AGENTS / "extract" / ".claude" / "guard.log"
    if src.exists():
        tmp = Path(tempfile.mkdtemp()) / "guard.log"
        shutil.copy(src, tmp)
        data = bytearray(tmp.read_bytes())
        i = data.index(b'"decision"') + 13
        data[i] = ord("X")
        tmp.write_bytes(bytes(data))
        broke = not chainlog.verify(tmp)[0]
        ok_all &= broke
        md.append(f"- Hash chain on a copy of extract's guard log with one byte edited: {'reports broken ✅' if broke else 'still verifies ❌'}")

    # 4: chains
    md += ["", "## 3. Hash-chained logs", "", "| Log | Lines | Chain |", "|---|---|---|"]
    for role in ROLES:
        for name in ("guard.log", "gate.log"):
            p = AGENTS / role / ".claude" / name
            if p.exists():
                good, n, bad = chainlog.verify(p)
                ok_all &= good
                md.append(f"| {role}/{name} | {n} | {'intact ✅' if good else f'broken at line {bad} ❌'} |")

    # 5: timeline
    md += ["", "## 4. Session timeline", "", "```"] + [f"{s['ts']}  {s['event']:<5} {s['role']:<10} {s['session']}" for s in sess] + ["```"]
    ext_end = max((s["ts"] for s in sess if s["role"] == "extract" and s["event"] == "end"), default=None)
    ev_start = min((s["ts"] for s in sess if s["role"] == "evals-data" and s["event"] == "start"), default=None)
    ext_after = [s for s in sess if s["role"] == "extract" and s["event"] == "start" and ev_start and s["ts"] >= ev_start]
    order_ok = bool(ext_end and ev_start and ext_end <= ev_start and not ext_after)
    ok_all &= order_ok
    md.append(f"extract ended {ext_end}; evals-data started {ev_start}; extract restarted after: {len(ext_after)} -> {'✅ ordering held' if order_ok else '❌'}")

    # 6: tests read-before-write
    md += ["", "## 5. Tests agent: read-before-write check", ""]
    troot = (AGENTS / "tests").resolve()
    tlog = read_jsonl(troot / ".claude" / "guard.log")

    def rel_to_clone(t):
        p = Path(str(t or ""))
        p = p if p.is_absolute() else troot / p
        try:
            return p.resolve().relative_to(troot).as_posix()
        except ValueError:
            return None

    tbase = (troot / ".claude" / "base").read_text().strip() if (troot / ".claude" / "base").exists() else "main"
    base_files = set(git("ls-tree", "-r", "--name-only", tbase, "--", "tests", cwd=troot).split())
    written = {rel_to_clone(e.get("target")) for e in tlog if e.get("tool") in ("Write", "Edit") and e.get("decision") == "allow"}
    reads = [rel_to_clone(e.get("target")) for e in tlog if e.get("tool") == "Read" and e.get("decision") == "allow"]
    suspicious = sorted({r for r in reads if r and r.startswith("tests/") and r not in written and r not in base_files})
    dirty = git("status", "--porcelain", cwd=troot).strip()
    ok_all &= not suspicious and not dirty
    md.append(f"Reads of tests/ files the agent neither wrote nor had in its base: {suspicious or 'none ✅'}")
    md.append(f"Untracked or modified files in the tests clone (possible conftest side effects): {dirty or 'none ✅'}")

    # 7: scorecard
    md += ["", "## 6. Agent scorecard (lean slice)", "",
           "| Role | Files on disk | Context pack words | Tool calls | Denied | Gate attempts | Turns | Cost USD | Minutes |", "|---|---|---|---|---|---|---|---|---|"]
    for role in ROLES:
        clone = AGENTS / role
        if not clone.exists():
            continue
        on_disk = sum(1 for p in clone.rglob("*") if p.is_file() and ".git" not in p.parts and "__pycache__" not in p.parts)
        pack = clone / "context" / f"{role}.md"
        words = len(pack.read_text().split()) if pack.exists() else "-"
        g = read_jsonl(clone / ".claude" / "guard.log")
        gates = read_jsonl(clone / ".claude" / "gate.log")
        turns = cost = mins = "-"
        tr = AGENTS / "logs" / (f"{role}.jsonl" if role != "evals-data" else "evals-data.json")
        results = [e for e in read_jsonl(tr) if e.get("type") == "result"] if role != "evals-data" else ([json.loads(tr.read_text())] if tr.exists() else [])
        if results:
            turns = sum(e.get("num_turns") or 0 for e in results)
            cost = round(sum(e.get("total_cost_usd") or 0 for e in results), 2)
            mins = round(sum(e.get("duration_ms") or 0 for e in results) / 60000, 1)
        md.append(f"| {role} | {on_disk} | {words} | {len(g)} | {sum(e.get('decision') == 'deny' for e in g)} | {len(gates)} | {turns} | {cost} | {mins} |")

    md += ["", f"**Overall: {'all checks passed ✅' if ok_all else 'some checks failed ❌ (see above)'}**", ""]
    out = REPO / "evidence" / "audit.md"
    out.parent.mkdir(exist_ok=True)
    out.write_text("\n".join(md))
    print("\n".join(md))
    sys.exit(0 if ok_all else 1)


if __name__ == "__main__":
    main()
